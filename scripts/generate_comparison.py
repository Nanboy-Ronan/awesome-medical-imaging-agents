#!/usr/bin/env python3
"""Validate curator evidence annotations and generate docs/comparison.md."""
import argparse
from datetime import date
from pathlib import Path
import re
import sys

import yaml

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = {
    'offline_benchmark': 'Offline benchmark',
    'offline_benchmark_expert_review': 'Offline benchmark + expert review',
    'retrospective_cohorts': 'Retrospective cohorts',
    'retrospective_datasets': 'Retrospective datasets',
    'synthetic_corruptions': 'Simulated corruptions on real volumes',
    'retrospective_external': 'Retrospective internal + external datasets',
    'retrospective_reports': 'Retrospective reports',
    'retrospective_downstream': 'Retrospective downstream evaluation',
    'curated_case_expert_review': 'Curated cases + expert review',
    'research_workflow_benchmark': 'Research workflow benchmark',
    'cross_domain_benchmark': 'Cross-domain benchmark',
    'simulated_workflow': 'Simulated acquisition workflow',
    'workstation_benchmark': 'Workstation benchmark on retrospective scans',
    'counterfactual_external': 'Counterfactual internal + external tests',
}
REQUIRED = ('id', 'label', 'title', 'paper_url', 'source_url', 'source_version',
            'group', 'task', 'mechanism', 'training', 'evaluation', 'evidence',
            'control_evidence', 'limitation', 'code_status', 'code_note',
            'review_basis', 'checked_at', 'reproduction_status')


def identity(url):
    match = re.search(r'arxiv\.org/(?:abs|pdf|html)/(\d{4}\.\d{4,5})', url)
    return match[1] if match else url.rstrip('/').casefold()


def validate(entries, papers):
    known = {identity(p.get('paper_url') or '') for p in papers}
    seen = set()
    paper_ids = set()
    for entry in entries:
        for key in REQUIRED:
            if not isinstance(entry.get(key), str) or not entry[key].strip():
                raise ValueError(f"{entry.get('id', '?')}: missing string field {key}")
        if not re.fullmatch(r'[A-Za-z0-9-]+', entry['id']) or entry['id'] in seen:
            raise ValueError(f"Invalid or duplicate id: {entry['id']}")
        seen.add(entry['id'])
        key = identity(entry['paper_url'])
        if key not in known or key in paper_ids:
            raise ValueError(f"Unknown or duplicate paper: {entry['paper_url']}")
        paper_ids.add(key)
        if entry['evidence'] not in EVIDENCE:
            raise ValueError(f"Unknown evidence label: {entry['evidence']}")
        if entry['code_status'] not in ('source_inspected', 'not_established'):
            raise ValueError(f"Unknown code status: {entry['code_status']}")
        for field in ('paper_url', 'source_url', 'code_url'):
            if entry.get(field) and not entry[field].startswith('https://'):
                raise ValueError(f"{entry['id']}: {field} must use HTTPS")
        if entry['code_status'] == 'source_inspected' and not entry.get('code_url'):
            raise ValueError(f"{entry['id']}: inspected source requires a repository URL")
        snapshot = entry.get('readme_snapshot')
        if snapshot and (not entry.get('code_url') or
                         snapshot.get('path') not in ('README.md', 'README.MD') or
                         not re.fullmatch(r'[0-9a-f]{40}', snapshot.get('sha', ''))):
            raise ValueError(f"{entry['id']}: invalid README content snapshot")
        if entry['reproduction_status'] != 'not_run':
            raise ValueError('Executed/reproduced statuses require a separate execution log and schema update')
        date.fromisoformat(entry['checked_at'])
    if not entries:
        raise ValueError('Comparison must contain at least one reviewed paper')


def cell(text):
    return text.replace('|', '\\|').replace('\n', ' ')


def render(entries):
    latest = max(e['checked_at'] for e in entries)
    lines = [
        '<!-- Generated by scripts/generate_comparison.py from data/comparison.yml. -->',
        '', '# Medical Imaging Agents: Comparison and Evidence', '',
        '[Main collection](../README.md) · [Monthly brief](briefs/2026-11.md) · '
        '[Review protocol](review-protocol.md) · [Structured annotations](../data/comparison.yml)', '',
        f'{len(entries)} selected works · Last source check: **{latest}**.', '',
        'Selected for coverage of agent mechanisms, imaging settings, and evaluation designs. '
        'This is an editorial reading guide, not a leaderboard or an exhaustive survey. '
        'Training, data, tools, budgets, and outcome definitions differ across papers; '
        'their headline scores should not be ranked together.', '',
        'Evidence labels describe the evaluated setting, not a quality grade. '
        'Expert review of retrospective outputs does not establish prospective clinical benefit. '
        'Controls marked as not audited remain unknown; absence of a verified control here does not mean '
        'the authors omitted it.', '',
        '**Resource audit:** “Source inspected” means the public repository tree and/or README were '
        'retrieved and inspected. It does not establish complete data, weights, licensing, installability, '
        'or reproducibility. “Not established” means the inspected sources did not establish an implementation '
        'link. No model, dataset download, environment installation, or paper reproduction was attempted '
        'for this edition. All independent reproduction statuses are **not run**.', '',
        '## Compare workflows', '',
    ]
    for group in dict.fromkeys(e['group'] for e in entries):
        lines += [f'### {group}', '',
                  '| Work | Task | Agent mechanism | Training | Evaluation |',
                  '|---|---|---|---|---|']
        for e in (e for e in entries if e['group'] == group):
            lines.append('| ' + ' | '.join([
                f"[{e['label']}](#{e['id'].lower()})",
                *[cell(e[k]) for k in ('task', 'mechanism', 'training', 'evaluation')],
            ]) + ' |')
        lines.append('')
    lines += ['## Evidence and resource ledger', '']
    for e in entries:
        code = (f"[Source inspected]({e['code_url']})" if e['code_status'] == 'source_inspected'
                else 'Implementation link not established in inspected sources')
        lines += [f"### {e['label']}", '', f"**{e['title']}**", '',
                  f"- Primary source: [{e['source_version']}]({e['source_url']}).",
                  f"- Evidence setting: {EVIDENCE[e['evidence']]}. {e['evaluation']}",
                  f"- Control evidence checked: {e['control_evidence']}",
                  f"- Interpretation / limit: {e['limitation']}",
                  f"- Code audit: {code}. {e['code_note']}",
                  f"- Independent reproduction: **not run**. Checked {e['checked_at']}; scope: {e['review_basis']}."]
        if e.get('readme_snapshot'):
            snapshot = e['readme_snapshot']
            lines.append(f"- Resource snapshot: `{snapshot['path']}` blob SHA `{snapshot['sha']}` "
                         '(recorded from the public source tree; not a release or execution hash).')
        lines.append('')
    lines += ['## Correct or extend a review', '',
              'Use the [evidence review issue form](https://github.com/Nanboy-Ronan/'
              'awesome-medical-imaging-agents/issues/new?template=evidence-review.yml) '
              'or submit a PR editing `data/comparison.yml`. Include the paper version, source '
              'section/table, repository revision, and any execution logs. See the '
              '[review protocol](review-protocol.md) for the distinction between author claims and '
              'independent checks. Regenerate this page after editing annotations.', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Validate without modifying output; fail on stale output')
    args = parser.parse_args()
    raw = yaml.safe_load((ROOT / 'data/comparison.yml').read_text())
    if raw.get('schema_version') != 1:
        sys.exit('Unsupported comparison schema version')
    entries = raw['entries']
    papers = yaml.safe_load((ROOT / 'data/papers.yml').read_text())['papers']
    try:
        validate(entries, papers)
    except (ValueError, TypeError) as error:
        sys.exit(str(error))
    output = ROOT / 'docs/comparison.md'
    generated = render(entries)
    if args.check:
        if not output.exists() or output.read_text() != generated:
            sys.exit('docs/comparison.md is missing or stale. Run: python scripts/generate_comparison.py')
        print(f'Comparison is current ({len(entries)} reviewed works).')
    else:
        output.write_text(generated)
        print(f'Wrote comparison for {len(entries)} reviewed works.')


if __name__ == '__main__':
    main()
